'use client';

import React from 'react';

export interface CardProps {
  title: string;
  value: string | number;
  subtitle?: string;
  icon?: React.ReactNode;
  iconBgColor?: string;
  iconColor?: string;
  textColor?: string;
  className?: string;
  onClick?: () => void;
  isClickable?: boolean;
}

export interface StatCardProps {
  cards: CardProps[];
  className?: string;
  gridCols?: 1 | 2 | 3 | 4;
}

export const Card: React.FC<CardProps> = ({
  title,
  value,
  subtitle,
  icon,
  iconBgColor = 'bg-blue-50',
  iconColor = 'text-blue-600',
  textColor = 'text-gray-900',
  className = '',
  onClick,
  isClickable = false,
}) => {
  const baseClasses = `bg-white p-5 sm:p-6 rounded-xl shadow-sm hover:shadow-md transition-shadow border-0`;
  const clickableClasses = isClickable || onClick ? 'cursor-pointer hover:bg-gray-50' : '';
  
  const formatValue = (val: string | number) => {
    if (typeof val === 'number') {
      return val.toLocaleString();
    }
    return val;
  };

  return (
    <div 
      className={`${baseClasses} ${clickableClasses} ${className}`}
      onClick={onClick}
    >
      <div className="flex items-center justify-between">
        <h3 className="text-sm font-medium text-gray-500">{title}</h3>
        {icon && (
          <div className={`p-2 rounded-lg ${iconBgColor} ${iconColor}`}>
            {icon}
          </div>
        )}
      </div>
      <p className={`text-2xl sm:text-3xl font-semibold ${textColor} mt-3`}>
        {formatValue(value)}
      </p>
      {subtitle && (
        <div className="mt-4 pt-4 border-t border-gray-100">
          <p className="text-xs text-gray-500">{subtitle}</p>
        </div>
      )}
    </div>
  );
};

export const StatCards: React.FC<StatCardProps> = ({
  cards,
  className = '',
  gridCols = 3,
}) => {
  const getGridClasses = () => {
    switch (gridCols) {
      case 1: return 'grid-cols-1';
      case 2: return 'grid-cols-1 md:grid-cols-2';
      case 3: return 'grid-cols-1 md:grid-cols-3';
      case 4: return 'grid-cols-1 md:grid-cols-4';
      default: return 'grid-cols-1 md:grid-cols-3';
    }
  };

  return (
    <div className={`grid ${getGridClasses()} gap-4 sm:gap-6 ${className}`}>
      {cards.map((card, index) => (
        <Card key={index} {...card} />
      ))}
    </div>
  );
};

